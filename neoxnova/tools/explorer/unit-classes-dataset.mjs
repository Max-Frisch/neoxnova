// unit-classes-dataset.mjs — turn the raw info-card capture (data/unit-info.json,
// written by `httpbot.mjs cards`) into the committed fixture
// testdata/niburus_unit_classes.json AND the generated Go table
// internal/game/unit_classes.go.
//
// Run from tools/explorer/:
//   node httpbot.mjs cards          # refresh data/unit-info.json
//   node unit-classes-dataset.mjs   # fold it into the fixture + Go table
//
// The card class strings are normalised to the Arsenal catalog's class keys:
// weapon {laser,ion,plasma,gravitational,standard}, armor/shield
// {light,medium,heavy}, engine {combustion,impulse,hyperspace}. Anything else
// (including a missing field) becomes "".
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const SRC = path.join(__dirname, 'data', 'unit-info.json');
const FIXTURE = path.resolve(__dirname, '../../testdata/niburus_unit_classes.json');
const GO = path.resolve(__dirname, '../../internal/game/unit_classes.go');

const WEAPON = { standard: 'standard', laser: 'laser', ion: 'ion', plasma: 'plasma', gravitational: 'gravitational' };
const ARMOR = { light: 'light', medium: 'medium', heavy: 'heavy' };
const SHIELD = { light: 'light', medium: 'medium', heavy: 'heavy' };
const ENGINE = { 'combustion engine': 'combustion', 'impulse engine': 'impulse', 'hyperspace engine': 'hyperspace' };

const norm = (v, table) => table[String(v == null ? '' : v).trim().toLowerCase()] || '';

const raw = JSON.parse(fs.readFileSync(SRC, 'utf8'));
if (!raw.units) throw new Error(`${SRC} has no units; run: node httpbot.mjs cards`);

const codes = Object.keys(raw.units).map(Number).sort((a, b) => a - b);
const units = {};
for (const code of codes) {
  const u = raw.units[code];
  // A unit may list several weapon rows (e.g. Galleon = Laser 10k + Ion 10k).
  const src = (u.weapons && u.weapons.length) ? u.weapons : (u.weaponType ? [{ type: u.weaponType, attack: 0 }] : []);
  const weapons = src
    .map((w) => ({ class: norm(w.type, WEAPON), attack: w.attack || 0 }))
    .filter((w) => w.class);
  units[code] = {
    name: u.name || '',
    weapon: weapons.length ? weapons[0].class : '',
    weapons,
    armor: norm(u.armorClass, ARMOR),
    shield: norm(u.shieldClass, SHIELD),
    engine: norm(u.engineClass, ENGINE),
  };
}

const fixture = {
  meta: {
    source: 'niburuspace.com unit information cards (game.php?page=information&id=<code>)',
    capturedAt: raw.updatedAt || new Date().toISOString(),
    note: 'Per-unit Arsenal upgrade classes. Card strings are normalised to the catalog keys; "" means the card declares no such class (cargo ships have no weapon, defenses no engine). Generated by tools/explorer/unit-classes-dataset.mjs.',
  },
  units,
};

fs.mkdirSync(path.dirname(FIXTURE), { recursive: true });
fs.writeFileSync(FIXTURE, JSON.stringify(fixture, null, 2));
console.log(`WROTE ${FIXTURE} (${codes.length} units)`);

const goStr = (s) => JSON.stringify(s);
const lines = [];
lines.push('// Code generated from testdata/niburus_unit_classes.json; DO NOT EDIT.');
lines.push('');
lines.push('package game');
lines.push('');
lines.push('// UnitClass is the set of Arsenal upgrade classes on a unit\'s information card');
lines.push('// (game.php?page=information&id=<code>). Values are normalised to the catalog');
lines.push('// class keys used by internal/game/arsenal.go: weapon');
lines.push('// {laser,ion,plasma,gravitational,standard}, armor/shield {light,medium,heavy},');
lines.push('// engine {combustion,impulse,hyperspace}. An empty string means the card');
lines.push('// declares no class for that slot (cargo ships have no weapon, defenses no');
lines.push('// engine).');
lines.push('//');
lines.push('// A unit can carry SEVERAL weapon types, each contributing its own base attack');
lines.push('// (e.g. 225 Galleon = Laser 10,000 + Ion 10,000); those are listed in Weapons.');
lines.push('// Weapon is the first (primary) weapon class, kept for callers that only need');
lines.push('// a single class.');
lines.push('type UnitClass struct {');
lines.push('\tWeapon  string');
lines.push('\tWeapons []WeaponClass');
lines.push('\tArmor   string');
lines.push('\tShield  string');
lines.push('\tEngine  string');
lines.push('}');
lines.push('');
lines.push('// WeaponClass is one weapon component of a unit: its Arsenal class and the');
lines.push('// base attack power it contributes (before tech/upgrade bonuses).');
lines.push('type WeaponClass struct {');
lines.push('\tClass  string');
lines.push('\tAttack int');
lines.push('}');
lines.push('');
lines.push('// unitClasses holds the declared classes for every ship (202-228) and defense');
lines.push('// (401-419). Codes absent from the map have no information card.');
lines.push('var unitClasses = map[string]UnitClass{');
for (const code of codes) {
  const u = units[code];
  let w = `Weapon: ${goStr(u.weapon)}`;
  if (u.weapons.length) {
    const parts = u.weapons.map((x) => `{Class: ${goStr(x.class)}, Attack: ${x.attack}}`).join(', ');
    w += `, Weapons: []WeaponClass{${parts}}`;
  }
  lines.push(`\t${goStr(String(code))}: {${w}, Armor: ${goStr(u.armor)}, Shield: ${goStr(u.shield)}, Engine: ${goStr(u.engine)}},`);
}
lines.push('}');
lines.push('');
lines.push('// UnitClassOf returns the declared upgrade classes for a unit code.');
lines.push('func UnitClassOf(code string) (UnitClass, bool) {');
lines.push('\tc, ok := unitClasses[code]');
lines.push('\treturn c, ok');
lines.push('}');
lines.push('');
lines.push('// UpgradeCodeForClass resolves a unit\'s declared class within an upgrade group');
lines.push('// (weapon|armor|shield|engine) to the Arsenal upgrade code that applies to it,');
lines.push('// or 0 when no catalog upgrade covers that class (e.g. "standard" weapons).');
lines.push('func UpgradeCodeForClass(group, class string) int {');
lines.push('\tif class == "" {');
lines.push('\t\treturn 0');
lines.push('\t}');
lines.push('\treturn upgradeCodeByClass[group+"/"+class]');
lines.push('}');
lines.push('');

fs.writeFileSync(GO, lines.join('\n'));
console.log(`WROTE ${GO}`);
